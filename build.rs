//! Bakes `assets/icons/*.svg` into the binary.
//!
//! The UI draws its icons through GPUI's asset source. A packaged SpritX (deb,
//! rpm, Arch package, Flatpak, AppImage) is a bare binary with no source tree
//! beside it, so the icons have to travel inside it — reading them from
//! `CARGO_MANIFEST_DIR` at runtime, which is what the first release did, only
//! worked when the app happened to run from the directory it was built in.

use std::env;
use std::fs;
use std::path::Path;

fn main() {
    let dir = Path::new("assets/icons");
    println!("cargo:rerun-if-changed={}", dir.display());
    println!("cargo:rerun-if-changed=build.rs");

    let mut files: Vec<String> = fs::read_dir(dir)
        .expect("assets/icons ships with the repository")
        .filter_map(|entry| entry.ok())
        .map(|entry| entry.file_name().to_string_lossy().into_owned())
        .filter(|name| name.ends_with(".svg"))
        .collect();
    files.sort();

    let mut table = String::from(
        "/// The icons in `assets/icons`, keyed by file stem. Generated by build.rs.\n\
         pub static ICONS: &[(&str, &[u8])] = &[\n",
    );
    for file in &files {
        let stem = file.trim_end_matches(".svg");
        // An absolute path: this file is written to OUT_DIR, so a relative
        // include would resolve against the wrong directory.
        table.push_str(&format!(
            "    ({stem:?}, include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/assets/icons/{file}\"))),\n"
        ));
    }
    table.push_str("];\n");

    let generated = Path::new(&env::var("OUT_DIR").expect("cargo sets OUT_DIR")).join("icons.rs");
    fs::write(&generated, table).expect("write the generated icon table");
}
